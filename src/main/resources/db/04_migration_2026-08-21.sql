SET NAMES utf8mb4;

-- ---------------------------------------------------------------------
-- 0. 스키마 드리프트 정리
--
--    01_schema.sql 이 엔티티보다 뒤처져 있다. 아래 두 컬럼은 코드가 이미 쓰고 있는데
--    DDL에는 없어서, 깨끗한 DB에 스키마를 새로 깔면 ddl-auto: validate 가 기동을
--    막는다. 이미 손으로 ALTER 해둔 서버라면 이 두 문장은 그냥 넘어간다.
-- ---------------------------------------------------------------------
ALTER TABLE appointments
    ADD COLUMN IF NOT EXISTS client_id VARCHAR(64) NULL
        COMMENT '프론트가 만든 일정 id("visit-2026-08-16")';

ALTER TABLE test_sheets
    ADD COLUMN IF NOT EXISTS nutrition_foods JSON NULL
        COMMENT '프론트 AI가 추천한 재료. 화면마다 다른 게 뜨지 않도록 저장해둔다';

-- ---------------------------------------------------------------------
-- 1. 판정 근거 보관 (전달사항 2번)
--
--    프론트 판정 엔진이 붙여 보낸 근거·출처·추천 질문을 저장한다.
--    저장하지 않으면 기록 탭에서 지난 검사지를 열었을 때 이것들이 통째로 사라진다.
--
--    컬럼을 쪼개지 않은 이유: 서버는 이 값을 읽거나 조건에 걸지 않고 그대로
--    돌려주기만 한다. 엔진이 계속 자라는 중이라 모양이 굳으면 그때 정규화한다.
-- ---------------------------------------------------------------------
ALTER TABLE test_results
    ADD COLUMN IF NOT EXISTS engine_status VARCHAR(20) NULL
        COMMENT 'safe|watch|recheck|indeterminate|alert|info_only|unsupported',
    ADD COLUMN IF NOT EXISTS engine_meta JSON NULL
        COMMENT '판정 근거·출처·인용문·추천 질문 원본(프론트 엔진 산출물)';

